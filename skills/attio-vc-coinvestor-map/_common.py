def render_markdown(meta: dict, report: ReportData) -> str:
    out: list[str] = []
    out.append(f"# Attio VC Co-Investor Map: {meta['fund_name']}")
    out.append("")
    out.append(f"**Workspace:** `{meta['workspace_slug']}` &nbsp;·&nbsp; **Source:** {meta['source_label']} &nbsp;·&nbsp; **Run:** {meta['run_ts']}")
    out.append("")
    out.append(meta["detection_note"])
    out.append(f"**Deals/investments scanned:** {report.total} ({meta['scope_note']}) &nbsp;·&nbsp; **Field(s) matched:** {meta['field_note']}")
    out.append("")
    out.append(
        "Relationship-density check on co-investor / syndicate tracking, across both pipeline and "
        "portfolio. This reports only what's in an explicit, human-entered field -- it does **not** "
        "replicate Affinity's own relationship-strength scoring (built on private email/calendar "
        "sync data no public API exposes). See SKILL.md for that scope boundary."
    )
    out.append("")
    out.append("---")
    out.append("")

    out.append(f"## Coverage: **{report.coverage_pct:.0f}%** ({report.found_count}/{report.total} deals have at least one co-investor logged)")
    out.append("")

    if report.total == 0:
        out.append("_No deals in scope to check._")
        out.append("")
    else:
        out.append("### Co-investor frequency (ranked)")
        out.append("")
        if not report.ranked:
            out.append("_No co-investor names found on any scanned deal -- the field is tracked but empty everywhere in scope._")
        else:
            out.append("| Rank | Co-investor | Appearances |")
            out.append("|---|---|---|")
            shown = report.ranked[:MAX_TABLE_ROWS]
            for i, (name, count) in enumerate(shown, start=1):
                out.append(f"| {i} | {name} | {count} |")
            remainder = len(report.ranked) - len(shown)
            if remainder > 0:
                out.append(f"| _(+{remainder} more)_ | | |")
        out.append("")

        out.append(f"### Gaps -- deals with zero co-investor data: {len(report.gaps)}")
        out.append("")
        if not report.gaps:
            out.append("Every scanned deal has at least one co-investor logged.")
        else:
            shown = report.gaps[:MAX_TABLE_ROWS]
            out.extend(f"- {name}" for name in shown)
            remainder = len(report.gaps) - len(shown)
            if remainder > 0:
                out.append(f"- (+{remainder} more)")
        out.append("")

    out.append("---")
    out.append("")
    out.append(
        "Generated by [5050-vc-skills](https://github.com/NachoLafuente/5050-vc-skills). "
        "Open source from [5050Growth](https://5050growth.com)."
    )
    return "\n".join(out)


def render_json(meta: dict, report: ReportData | None) -> dict:
    base = {
        "workspace": {"slug": meta["workspace_slug"], "name": meta["fund_name"]},
        "source": meta["source_label"],
        "detection": meta["detection_note"],
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }
    if report is None:
        base["field_tracked"] = False
        base["keywords_checked"] = COINVESTOR_KEYWORDS
        return base

    base["field_tracked"] = True
    base["scope"] = meta["scope_note"]
    base["field_note"] = meta["field_note"]
    base["coverage"] = {
        "total_deals": report.total,
        "with_coinvestor": report.found_count,
        "coverage_pct": round(report.coverage_pct, 1),
    }
    base["ranked_coinvestors"] = [{"name": n, "count": c} for n, c in report.ranked]
    base["gaps"] = report.gaps
    base["deals"] = [{"name": d.name, "status": d.status, "coinvestors": d.names} for d in report.deals]
    return base
