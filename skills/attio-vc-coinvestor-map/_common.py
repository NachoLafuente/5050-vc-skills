"""
Source-agnostic internals for attio-vc-coinvestor-map: keyword list, report
data model, and markdown/JSON rendering shared by both backends (_attio.py,
_affinity.py).

This module never touches the network. Each backend detects its own
platform's co-investor field, fetches records/entries, and normalizes the
result into DealRecord objects defined here; everything downstream (coverage
math, the ranked frequency table, rendering) is identical regardless of
source.

Scope boundary, stated here because it governs how this module reports
things: this skill only ever reports what's in an explicit, human-entered
co-investor/syndicate field. It does not replicate Affinity's own
relationship-strength/interaction-scoring product (built on private
email/calendar sync data no public API exposes) -- see SKILL.md.

Read-only: no API calls anywhere in this file.
"""

from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime, timezone

# Matched as whole phrases (word-boundary, case-insensitive) against
# attribute/field titles -- not against note text or free text values.
COINVESTOR_KEYWORDS = [
    "co-investor",
    "co investor",
    "coinvestor",
    "syndicate",
    "other investors",
    "round participants",
]

MAX_TABLE_ROWS = 20  # markdown tables truncate at this many rows


def _matches_keyword(haystack: str, keyword: str) -> bool:
    return re.search(r"\b" + re.escape(keyword) + r"s?\b", haystack) is not None


def field_title_matches(title: str) -> bool:
    low = (title or "").lower().replace("_", " ").replace("-", " ")
    return any(_matches_keyword(low, kw) for kw in COINVESTOR_KEYWORDS)


@dataclass
class DealRecord:
    """One deal/investment, source-agnostic: a display name plus whatever
    co-investor names either backend could read off the matched field(s).
    Empty `names` means the field is tracked in this workspace but blank on
    this specific record -- that's the "gap" this skill flags.
    """

    key: str
    name: str
    names: list[str] = field(default_factory=list)

    @property
    def status(self) -> str:
        return "found" if self.names else "empty"


@dataclass
class ReportData:
    total: int
    found_count: int
    coverage_pct: float
    ranked: list[tuple[str, int]]
    gaps: list[str]
    deals: list[DealRecord]


def build_report(deals: list[DealRecord]) -> ReportData:
    total = len(deals)
    found = sum(1 for d in deals if d.names)
    coverage_pct = (found / total * 100) if total else 0.0
    freq: Counter[str] = Counter()
    for d in deals:
        for n in d.names:
            freq[n] += 1
    ranked = freq.most_common()
    gaps = [d.name for d in deals if not d.names]
    return ReportData(total=total, found_count=found, coverage_pct=coverage_pct, ranked=ranked, gaps=gaps, deals=deals)


