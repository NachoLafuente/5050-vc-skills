#!/usr/bin/env python3
"""
attio-vc-ic-pipeline-prep: the pipeline-status open of an IC meeting for a
VC/PE fund's Attio deal pipeline -- a 0-100 dealflow-hygiene grade (source-of-
intro coverage, thesis/classification coverage, stage-gate hygiene,
interaction coverage) followed by a written digest of what moved since the
last check-in (new deals, deals that advanced a stage, deals gone stale,
DD/activity delta from logged Notes).

This is the merge of two formerly-separate skills, attio-vc-pipeline-audit
(the grade) and attio-vc-pipeline-movement (the digest) -- real ICs open with
exactly this pair before individual deal votes start, so they now render as
one report instead of two. It is NOT a per-deal investment memo; for that see
the sibling skill attio-vc-ic-memo-prep.

Usage:
    ATTIO_API_KEY=<token> python ic_pipeline_prep.py
    python ic_pipeline_prep.py --token <token>
    python ic_pipeline_prep.py --object investments
    python ic_pipeline_prep.py --stale-days 45
    python ic_pipeline_prep.py --days 7
    python ic_pipeline_prep.py --json
    python ic_pipeline_prep.py --full

Output: markdown report to stdout (or JSON with --json). Exit code 0 always
(this is a report, not a gate).

Default mode samples up to 500 deal records and up to 500 notes (a handful of
read-only API calls). --full paginates every record and every note (more
calls, exact counts). Strictly read-only: GET and POST-query calls only. No
PATCH, PUT, or POST-write calls appear anywhere in this skill.

Auto-detects the deal/investment/opportunity object by api_slug/noun matching;
override with --object <slug> if detection is ambiguous or picks the wrong
object. Attribute and stage detection are keyword-based against whatever
objects/attributes actually exist in the connected workspace -- nothing here
is hardcoded to one fund's schema. See _common.py, _hygiene.py, and
_movement.py for the detection/scoring logic itself (split out of this file
because two logics now share one skill folder -- see _common.py's docstring).

Records, stage statuses, and Notes are each fetched exactly once here and
shared between the hygiene grade and the movement digest, instead of each
half independently re-fetching them the way the two standalone scripts used
to.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timedelta, timezone

import requests

import _common as common
import _hygiene as hygiene
import _movement as movement
import _vc_config as vc_config

DEFAULT_STALE_DAYS = 30
DEFAULT_DAYS = 14


def render(
    ws: dict,
    hygiene_sections: list[hygiene.Section],
    hygiene_total: int,
    buckets: list[movement.Bucket],
    dd: movement.DDSection,
    summary: str,
    meta: dict,
) -> str:
    name = ws.get("workspace_name", "Unknown")
    slug = ws.get("workspace_slug", "")
    out: list[str] = []
    out.append(f"# Attio VC IC Pipeline Prep: {name}")
    out.append("")
    out.append(f"**Workspace:** `{slug}` &nbsp;·&nbsp; **Run:** {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    out.append("")
    out.append(meta["detection_note"])
    scope_note = "all records" if meta["full_scan"] else f"up to {common.SAMPLE_LIMIT}-record sample"
    out.append(
        f"**Records scanned:** {meta['records_scanned']} ({scope_note}) &nbsp;·&nbsp; "
        f"**Stale threshold:** {meta['stale_days']} days &nbsp;·&nbsp; "
        f"**Movement window:** last {meta['days']} days"
    )
    out.append("")
    out.append(
        "This is the pipeline-status open of an IC meeting -- hygiene grade first, then what "
        "moved since the last check-in. It is **not** a per-deal investment memo; see the sibling "
        "skill `attio-vc-ic-memo-prep` for that."
    )
    out.append("")
    out.append("---")
    out.append("")
    out.extend(hygiene.render_hygiene(hygiene_sections, hygiene_total))
    out.append("---")
    out.append("")
    out.extend(movement.render_movement(buckets, dd, summary, meta["days"]))
    out.append("---")
    out.append("")
    out.append(
        "Generated by [5050-vc-skills](https://github.com/NachoLafuente/5050-vc-skills). "
        "Open source from [5050Growth](https://5050growth.com)."
    )
    return "\n".join(out)


def render_json(
    ws: dict,
    meta: dict,
    hygiene_sections: list[hygiene.Section],
    hygiene_total: int,
    buckets: list[movement.Bucket],
    dd: movement.DDSection,
    summary: str,
) -> str:
    return json.dumps(
        {
            "workspace": {
                "name": ws.get("workspace_name"),
                "slug": ws.get("workspace_slug"),
                "id": ws.get("workspace_id"),
            },
            "object": {
                "slug": meta["object_slug"],
                "label": meta["object_label"],
                "detection": meta["detection_note"],
            },
            "records_scanned": meta["records_scanned"],
            "full_scan": meta["full_scan"],
            "stale_days": meta["stale_days"],
            "movement_window_days": meta["days"],
            "hygiene": hygiene.hygiene_to_dict(hygiene_sections, hygiene_total),
            "movement": movement.movement_to_dict(buckets, dd, summary, meta["days"]),
            "generated_at": datetime.now(timezone.utc).isoformat(),
        },
        indent=2,
    )


def main() -> int:
    p = argparse.ArgumentParser(
        description=(
            "Pipeline-status open for an IC meeting: hygiene grade + movement digest for a "
            "VC/PE fund's Attio deal pipeline"
        )
    )
    p.add_argument("--token", help="Attio API token (default: $ATTIO_API_KEY or $ATTIO_OAUTH2)")
    p.add_argument("--object", help="Explicit deal/investment object slug. Overrides auto-detection and any cached config.")
    p.add_argument(
        "--config",
        help="Path to a saved workspace config (default: .vc-skills-config/<workspace-slug>.json). "
        "See README's 'First run' section and this skill's SKILL.md.",
    )
    p.add_argument(
        "--detect-only",
        action="store_true",
        help="Auto-detect the deal object and its candidate closed-stage statuses only, print as "
        "JSON, and exit -- no record/note calls made, no grade or digest computed. Used for "
        "first-run setup; see README.",
    )
    p.add_argument(
        "--stale-days",
        type=int,
        default=None,
        help=(
            "Days without an update before an active-stage deal counts as stale in the hygiene "
            f"grade (default: {DEFAULT_STALE_DAYS}, or a cached config's stale_days if set)"
        ),
    )
    p.add_argument(
        "--days",
        type=int,
        default=DEFAULT_DAYS,
        help=f"Lookback window in days for the movement digest (default: {DEFAULT_DAYS})",
    )
    p.add_argument("--json", action="store_true", help="Output JSON instead of markdown")
    p.add_argument(
        "--full",
        action="store_true",
        help="Paginate every record and every note instead of sampling. Slower, exact counts.",
    )
    args = p.parse_args()

    token = args.token or os.environ.get("ATTIO_API_KEY") or os.environ.get("ATTIO_OAUTH2")
    if not token:
        print("error: provide --token or set ATTIO_API_KEY", file=sys.stderr)
        return 2

    try:
        ws = common.fetch_self(token)
    except requests.HTTPError as e:
        print(f"error: auth failed (HTTP {e.response.status_code}). Token invalid or revoked.", file=sys.stderr)
        return 2

    workspace_slug = ws.get("workspace_slug", "")
    objects = common.fetch_objects(token)
    config = None if args.detect_only else vc_config.load_config(workspace_slug, args.config)

    if args.object:
        object_slug = args.object
        matched = next((o for o in objects if o.get("api_slug") == object_slug), None)
        object_label = (matched.get("singular_noun") if matched else None) or object_slug.title()
        detection_note = f"Using object `{object_slug}` (explicit `--object` override)."
    elif config and config.get("object"):
        object_slug = config["object"]
        matched = next((o for o in objects if o.get("api_slug") == object_slug), None)
        object_label = (matched.get("singular_noun") if matched else None) or object_slug.title()
        detection_note = (
            f"Using object `{object_slug}` from cached config "
            f"(`{args.config or vc_config.default_config_path(workspace_slug)}`)."
        )
    else:
        detected, candidates = common.detect_deal_object(objects)
        if not detected:
            hint = f" Candidates seen: {', '.join(candidates)}." if candidates else ""
            print(
                "error: could not confidently identify a deal/investment object in this "
                f"workspace's schema.{hint} Re-run with --object <slug>.",
                file=sys.stderr,
            )
            return 2
        object_slug = detected.get("api_slug")
        object_label = detected.get("singular_noun") or object_slug.title()
        detection_note = f"Auto-detected deal object: `{object_slug}` ({object_label})."

    try:
        attrs = common.fetch_attributes(token, object_slug)
    except requests.HTTPError as e:
        status = getattr(e.response, "status_code", "?")
        print(f"error: could not read attributes for object '{object_slug}' (HTTP {status}).", file=sys.stderr)
        return 2

    if args.detect_only:
        stage_attr = common.find_stage_attribute(attrs)
        closed_guess: list[str] = []
        all_status_titles: list[str] = []
        stage_slug_out = None
        if stage_attr is not None:
            stage_slug_out = stage_attr.get("api_slug")
            try:
                statuses = common.fetch_statuses(token, object_slug, stage_slug_out)
                all_status_titles = [s.get("title") for s in statuses if s.get("title")]
                closed_guess = sorted(common.classify_closed_statuses(statuses))
            except requests.HTTPError:
                pass
        print(
            json.dumps(
                {
                    "source": "attio",
                    "workspace_slug": workspace_slug,
                    "object": object_slug,
                    "object_candidates": None if args.object else common.detect_deal_object(objects)[1],
                    "stage_attribute": stage_slug_out,
                    "status_titles_all": all_status_titles,
                    "closed_status_titles_guess": closed_guess,
                    "stale_days_default": DEFAULT_STALE_DAYS,
                    "note": (
                        "Confirm `object`, `closed_status_titles_guess`, and `stale_days` with the "
                        "human, then save the confirmed values as "
                        f".vc-skills-config/{workspace_slug}.json. No records or notes were fetched, "
                        "no grade or digest was computed."
                    ),
                },
                indent=2,
            )
        )
        return 0

    try:
        records = common.fetch_records(token, object_slug, full=args.full)
    except requests.HTTPError as e:
        status = getattr(e.response, "status_code", "?")
        print(f"error: could not read records for object '{object_slug}' (HTTP {status}).", file=sys.stderr)
        return 2

    stale_days = args.stale_days if args.stale_days is not None else (config or {}).get("stale_days", DEFAULT_STALE_DAYS)

    # --- Stage-attribute + closed-status detection, done once and shared -----
    stage_attr = common.find_stage_attribute(attrs)
    closed_titles: set[str] | None = None
    stage_error: str | None = None
    stage_skip_note = (
        "No clear pipeline-stage (status-type) attribute detected on this object -- skipped. "
        "This workspace may model stage differently, or have multiple status fields with "
        "ambiguous names."
    )
    stage_ok = False
    stage_slug = None

    if stage_attr is not None:
        stage_slug = stage_attr.get("api_slug")
        stage_label = stage_attr.get("title") or stage_slug
        if config and config.get("closed_status_titles"):
            closed_titles = set(config["closed_status_titles"])
            stage_ok = True
        else:
            try:
                statuses = common.fetch_statuses(token, object_slug, stage_slug)
                closed_titles = common.classify_closed_statuses(statuses)
                stage_ok = True
            except requests.HTTPError:
                stage_error = f"Could not read status options for `{stage_label}` -- skipped."
                stage_skip_note = stage_error

    # --- Notes, fetched once and shared -------------------------------------
    notes: list[dict] | None
    notes_error: str | None
    try:
        notes = common.fetch_notes(token, object_slug, full=args.full)
        notes_error = None
    except requests.HTTPError as e:
        status = getattr(e.response, "status_code", "?")
        notes = None
        notes_error = f"Could not read Notes (HTTP {status}) -- token may lack note read scope. Skipped."

    if notes is not None:
        all_noted_ids = {n.get("parent_record_id") for n in notes if n.get("parent_record_id")}
    else:
        all_noted_ids = None

    movement_cutoff = datetime.now(timezone.utc) - timedelta(days=args.days)
    if notes is not None:
        noted_ids_window, total_notes_window = movement.notes_in_window(notes, movement_cutoff)
    else:
        noted_ids_window, total_notes_window = set(), 0

    # --- Part 1: hygiene grade ------------------------------------------------
    hygiene_sections = [
        hygiene.score_source_of_intro(attrs, records),
        hygiene.score_thesis_classification(attrs, records),
        hygiene.score_stage_gate_hygiene(records, stage_attr, closed_titles, stage_error, stale_days),
        hygiene.score_interaction_coverage(records, all_noted_ids, notes_error),
    ]
    applicable = [s for s in hygiene_sections if s.applicable]
    total_score = sum(s.score for s in applicable)
    total_max = sum(s.max_score for s in applicable)
    hygiene_total = round(total_score / total_max * 100) if total_max else 0

    # --- Part 2: movement digest ----------------------------------------------
    new_lines, new_count = movement.find_new_deals(records, movement_cutoff)
    new_bucket = movement.Bucket(name="New deals", count=new_count, items=new_lines)

    active_records: list[dict] = []
    if stage_ok:
        active_records = common.active_stage_records(records, stage_slug, closed_titles)
        adv_lines, adv_count = movement.find_advanced_stage(records, stage_slug, movement_cutoff)
        advanced_bucket = movement.Bucket(name="Advanced a stage", count=adv_count, items=adv_lines)
        stale_lines, stale_count = movement.find_stale_deals(active_records, noted_ids_window, movement_cutoff)
        stale_bucket = movement.Bucket(name="Gone stale", count=stale_count, items=stale_lines)
    else:
        advanced_bucket = movement.Bucket(
            name="Advanced a stage", count=0, applicable=False, findings=[stage_skip_note]
        )
        stale_bucket = movement.Bucket(name="Gone stale", count=0, applicable=False, findings=[stage_skip_note])

    dd_findings: list[str] = []
    if notes is not None and not args.full:
        dd_findings.append(
            "Notes are sampled in the same paginated order Attio returns them in, not "
            "guaranteed to correlate with recency -- use --full for an exact figure on a "
            "note-heavy workspace."
        )
    if notes is not None and not stage_ok:
        dd_findings.append(
            "Zero-DD-activity list needs a detected pipeline-stage attribute to know which deals "
            "are active -- not shown. " + stage_skip_note
        )

    if notes is not None:
        zero_items, zero_count = (
            movement.find_zero_dd_active(active_records, noted_ids_window) if stage_ok else ([], 0)
        )
        dd = movement.DDSection(
            total_notes=total_notes_window,
            zero_count=zero_count,
            zero_items=zero_items,
            applicable=True,
            findings=dd_findings,
        )
    else:
        dd = movement.DDSection(total_notes=0, zero_count=0, applicable=False, findings=[notes_error])

    summary = movement.build_summary(new_count, advanced_bucket.count, stale_bucket.count, total_notes_window, args.days)
    buckets = [new_bucket, advanced_bucket, stale_bucket]

    meta = {
        "object_slug": object_slug,
        "object_label": object_label,
        "detection_note": detection_note,
        "records_scanned": len(records),
        "full_scan": args.full,
        "stale_days": stale_days,
        "days": args.days,
    }

    if args.json:
        print(render_json(ws, meta, hygiene_sections, hygiene_total, buckets, dd, summary))
    else:
        print(render(ws, hygiene_sections, hygiene_total, buckets, dd, summary, meta))
    return 0


if __name__ == "__main__":
    sys.exit(main())
